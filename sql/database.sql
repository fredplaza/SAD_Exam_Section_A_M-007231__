-- ==========================================
-- ICT SERVICE REQUEST MANAGEMENT SYSTEM
-- SUPABASE DATABASE SCRIPT
-- ==========================================


-- ==========================================
-- CREATE SERVICE REQUEST TABLE
-- ==========================================


CREATE TABLE service_requests (

    id BIGINT
    GENERATED BY DEFAULT AS IDENTITY
    PRIMARY KEY,


    requester_name TEXT
    NOT NULL,


    department TEXT
    NOT NULL,


    category TEXT
    NOT NULL,


    description TEXT
    NOT NULL,


    priority TEXT
    NOT NULL
    CHECK(
        priority IN
        ('Low','Medium','High')
    ),


    status TEXT
    DEFAULT 'Pending'
    CHECK(
        status IN
        ('Pending',
         'In Progress',
         'Completed')
    ),


    created_at TIMESTAMPTZ
    DEFAULT NOW(),


    user_id UUID
    REFERENCES auth.users(id)

);



-- ==========================================
-- ENABLE ROW LEVEL SECURITY
-- ==========================================


ALTER TABLE service_requests
ENABLE ROW LEVEL SECURITY;



-- ==========================================
-- VIEW POLICY
-- Authenticated users can view requests
-- ==========================================


CREATE POLICY
"Authenticated users can view requests"

ON service_requests

FOR SELECT

TO authenticated

USING(true);



-- ==========================================
-- INSERT POLICY
-- User can only create own requests
-- ==========================================


CREATE POLICY
"Users can insert own requests"

ON service_requests

FOR INSERT

TO authenticated

WITH CHECK
(
    auth.uid() = user_id
);



-- ==========================================
-- UPDATE POLICY
-- User can update own requests
-- ==========================================


CREATE POLICY
"Users can update own requests"

ON service_requests

FOR UPDATE

TO authenticated

USING
(
    auth.uid() = user_id
);



-- ==========================================
-- DELETE POLICY
-- User can delete own requests
-- ==========================================


CREATE POLICY
"Users can delete own requests"

ON service_requests

FOR DELETE

TO authenticated

USING
(
    auth.uid() = user_id
);

